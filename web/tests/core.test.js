// Tests for the core engines: conjugation, spaced repetition, storage. Run: node web/tests/core.test.js
global.window = global;
const path = require("path");
for (const f of ["verbs_a1", "vocab_a1_1", "vocab_a1_2", "vocab_a1_3", "words_a1"]) require(path.join(__dirname, "../data/" + f + ".js"));
const C = require("../js/core/conjugate.js");
const SRS = require("../js/core/srs.js");
const L = require("../js/core/lexicon.js");
const mem = {}; global.localStorage = { getItem: (k) => mem[k] || null, setItem: (k, v) => { mem[k] = v; } };
const Store = require("../js/core/store.js");
let fail = 0;
const ok = (c, m) => { if (c) console.log("  ok   " + m); else { fail++; console.error("  FAIL " + m); } };
const V = Object.fromEntries(DQ_DATA.verbs.map((v) => [v.inf, v]));
console.log("Conjugation");
ok(C.present(V.arbeiten).join(",") === "arbeite,arbeitest,arbeitet,arbeiten,arbeitet,arbeiten", "arbeiten: e-insertion");
ok(C.present(V["heißen"])[1] === "heißt", "du heißt");
ok(C.present(V.kennen)[1] === "kennst", "du kennst (no e after nn)");
ok(C.present(V["öffnen"])[2] === "öffnet", "er öffnet");
ok(C.present(V.einkaufen)[0] === "kaufe ein", "separable prefix at the end");
ok(C.present(V["sich freuen"])[3] === "freuen uns", "reflexive pronoun");
ok(C.perfekt(V.fahren)[0] === "bin gefahren", "fahren → sein");
ok(C.preteritum(V.finden)[1] === "fandest", "du fandest");
ok(C.imperative(V.nehmen)[0] === "nimm!", "Nimm!");
ok(C.imperative(V.fahren)[0] === "fahr!", "Fahr! (no umlaut)");
ok(C.index(DQ_DATA.verbs).get("isst").inf === "essen", "isst → essen");
console.log("Lexicon");
const lex = L.build(DQ_DATA);
ok(lex.length > 350, lex.length + " entries");
ok(lex.filter((e) => e.type === "noun").every((e) => e.art === null || ["der", "die", "das"].includes(e.art)), "every noun has a valid article");
ok(new Set(lex.map((e) => e.id)).size === lex.length, "unique ids");
const forms = L.indexForms(lex, C);
ok(forms.get("buecher").de === "Buch", "plural form → lemma (anti-duplicate)");
console.log("Spaced repetition");
const now = Date.now(), DAY = SRS.DAY;
let c = SRS.newCard(now);
c = SRS.schedule(c, 4, now); ok(c.int === 1, "first success → 1 day");
c = SRS.schedule(c, 4, now + DAY); ok(c.int === 6, "second → 6 days");
const late = SRS.schedule(c, 4, now + 40 * DAY); ok(late.int > c.int, "late review rewarded, not punished (" + late.int + " d)");
const again = SRS.schedule(c, 1, now + 7 * DAY); ok(again.reps === 0 && again.lapses === 1, "forgotten → back to learning");
ok(SRS.status({ rec: late, rcl: late, use: late }, now + 41 * DAY) !== "unknown", "status computed");
console.log("Storage");
Store.load(); const p = Store.create("Test", "fr"); p.cards.x = { rec: c }; Store.save();
const backup = Store.exportJSON();
Store.remove(p.id); ok(!Store.profile(), "profile deleted");
const r = Store.importJSON(backup); ok(r.added === 1 && Store.profile().cards.x, "backup restored without loss");
console.log(fail ? fail + " FAILED" : "ALL TESTS PASSED"); process.exit(fail ? 1 : 0);
