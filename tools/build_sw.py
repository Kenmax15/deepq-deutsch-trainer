"""Write web/sw.js: a service worker that pre-caches every file of the app so it works offline
once installed (PWA). Run after changing any file:  python tools/build_sw.py"""
import hashlib
from pathlib import Path

WEB = Path(__file__).resolve().parents[1] / "web"
skip = {"sw.js"}
files = sorted(str(p.relative_to(WEB)).replace("\\", "/") for p in WEB.rglob("*")
               if p.is_file() and p.name not in skip and "tests" not in p.parts and p.suffix not in {".md", ".py"} and p.name != "manifest.json")
h = hashlib.sha1()
for f in files:
    h.update(f.encode()); h.update((WEB / f).read_bytes())
version = h.hexdigest()[:10]
listing = ",\n  ".join(f'"./{f}"' for f in ["", *files] if True)
(WEB / "sw.js").write_text(f'''/* DeepQ Deutsch Trainer — offline cache (generated by tools/build_sw.py). */
const CACHE = "dq-{version}";
const FILES = [
  {listing}
];
self.addEventListener("install", (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener("activate", (e) => e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener("fetch", (e) => {{
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then((r) => r || fetch(e.request)));
}});
self.addEventListener("notificationclick", (e) => {{
  e.notification.close();
  const action = e.action || "learn", id = (e.notification.data || {{}}).id;
  e.waitUntil(self.clients.matchAll({{ type: "window", includeUncontrolled: true }}).then((cs) => {{
    const c = cs[0];
    if (c) {{ c.postMessage({{ action, id }}); return c.focus(); }}
    return self.clients.openWindow("./index.html#/" + (action === "learn" && id ? "dict/" + id : "home"));
  }}));
}});
''', encoding="utf-8")
print(len(files), "files, version", version)
